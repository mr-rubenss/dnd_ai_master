// Сверка текста ведущего с состоянием: текст не может обещать того, чего нет в игре. Если в рассказе за ход герой
// что-то получил, кого-то победил или потерял хиты, а соответствующих изменений (инструментов) не было — ведущий
// получает короткую просьбу привести текст и состояние в соответствие (один раз за ход, masterTurn.ts).
// Эвристика по словам рассказа (второе лицо, «ты»): отрицания («не находишь») не считаются. Чистые функции.
import type { AiToolCall } from '../ai/types'
import type { ToolOutcome } from './masterTools'
import type { TurnDelta } from './turnChanges'

export type ClaimKind = 'gain' | 'victory' | 'hp-loss'

/** Слова, по которым видно, что рассказ что-то утверждает о листе или мире. */
export const CLAIM_PATTERNS: Record<ClaimKind, RegExp[]> = {
  gain: [
    /(?<!не\s)(?<!ничего\s)(?<!\p{L})(?:находишь|подбираешь|забираешь себе|прикарманиваешь|становишься обладателем|становишься владельцем)\s+(?!взглядом|глазами|его|её|их|в\s+себе|время|силы|слова|ответ)/iu,
    /(?<!не\s)(?<!\p{L})получаешь\s+(?!\d+\s+(?:урона|хит)|урон|преимуществ|помех|удар|ран|отказ|ответ|возможность|время|кивок|взгляд)/iu,
    /(?<!не\s)(?<!\p{L})(?:кладёшь|кладешь|прячешь|убираешь|складываешь)\s+(?:\S+\s+){0,3}?в\s+(?:свою\s+)?(?:сумку|карман|мешок|рюкзак|кошел[её]к)/iu,
    /(?<!не\s)(?<!\p{L})(?:отдаёт|отдает|протягивает|вручает|дарит|передаёт|передает|отсыпает|отсчитывает|суёт|сует|жалует)\s+(?:тебе|вам)(?!\p{L})/iu,
    /(?:у\s+тебя|в\s+(?:твоей\s+)?сумке|в\s+(?:твоём|твоем)\s+кармане)\s+(?:вдруг\s+)?(?:оказывается|появляется|обнаруживается)/iu,
  ],
  victory: [
    /(?<!не\s)(?<!\p{L})(?:убиваешь|сражаешь|повергаешь|побеждаешь|одолеваешь|приканчиваешь|обезглавливаешь|разрубаешь)(?!\p{L})/iu,
    /(?<!\p{L})(?:падает|рушится|валится)\s+замертво(?!\p{L})/iu,
    /(?<!\p{L})(?:испускает\s+дух|бездыханн\S*|погибает\s+от\s+твоего)/iu,
  ],
  'hp-loss': [
    /(?<!не\s)(?<!\p{L})(?:теряешь|получаешь)\s+\d+\s+(?:хит|урон|единиц)/iu,
    /(?<!\p{L})(?:ранит|ранил|ранила|ранили|задевает|задел[аи]?)\s+тебя(?!\p{L})/iu,
    /(?<!\p{L})ты\s+(?:ранен|ранена|истекаешь\s+кровью)(?!\p{L})/iu,
  ],
}

export const CLAIM_TEXT: Record<ClaimKind, string> = {
  gain: 'в рассказе герой что-то получил (предмет или деньги), но give_item / change_gold не вызывались — в листе ничего нового',
  victory: 'в рассказе противник убит или побеждён, но бросков движка за ход не было — гибель и победа только по броскам',
  'hp-loss': 'в рассказе герой ранен или потерял хиты, но change_hp не вызывался — хиты в листе прежние',
}

/** Что утверждает текст (виды утверждений). */
export function textClaims(text: string): ClaimKind[] {
  return (Object.keys(CLAIM_PATTERNS) as ClaimKind[]).filter((kind) => CLAIM_PATTERNS[kind].some((re) => re.test(text)))
}

/** Инструменты, которые бросают кубики движка (победа может опираться на их итог). */
const ROLL_TOOLS = new Set(['request_check', 'cast_spell', 'use_feature', 'change_hp'])

/**
 * Расхождения рассказа с состоянием за ход: утверждение есть, а изменения (или броска) нет.
 * delta — изменения листов за ход; toolCalls — вызовы инструментов за ход с итогом движка.
 */
export function claimProblems(text: string, delta: TurnDelta, toolCalls: readonly { call: AiToolCall; outcome: ToolOutcome }[]): string[] {
  const ok = toolCalls.filter((t) => t.outcome.ok)
  const gained = [...delta.money.values()].some((v) => v > 0) || [...delta.items.values()].some((m) => [...m.values()].some((v) => v > 0))
  const hurt = [...delta.hp.values()].some((v) => v < 0)
  const rolled = ok.some((t) => ROLL_TOOLS.has(t.call.name))
  return textClaims(text)
    .filter((kind) => (kind === 'gain' ? !gained : kind === 'hp-loss' ? !hurt : !rolled))
    .map((kind) => CLAIM_TEXT[kind])
}

/** Просьба к ведущему привести текст и состояние в соответствие (один раз за ход). */
export function claimReminder(problems: string[]): string {
  return (
    '[Код игры] Текст не совпадает с состоянием игры: ' +
    problems.join('; ') +
    '. Текст не может обещать того, чего нет в состоянии. Если это честно по правилам (есть источник, нужен бросок) — ' +
    'вызови нужный инструмент (give_item/change_gold с source, request_check, change_hp с dice). Если нет — напиши ответ ' +
    'заново целиком, без этого утверждения: игрок только попытался, исход решают правила. Не упоминай, что исправляешь. ' +
    'Если всё исправлено инструментами и текст верен — ответь пустым текстом.'
  )
}
