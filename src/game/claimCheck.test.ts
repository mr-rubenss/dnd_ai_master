import { describe, expect, it } from 'vitest'
import { textClaims } from './claimCheck'

describe('утверждения рассказа (сверка текста с состоянием)', () => {
  it.each([
    ['Ты находишь в сундуке непробиваемый доспех.', ['gain']],
    ['Трактирщик отдаёт тебе всё золото из кассы.', ['gain']],
    ['У тебя в сумке вдруг оказывается зелье.', ['gain']],
    ['Ты кладёшь кинжал в сумку.', ['gain']],
    ['Лиара, влюбившись, дарит тебе своё кольцо.', ['gain']],
    ['Ты одним ударом убиваешь дракона.', ['victory']],
    ['Огр падает замертво.', ['victory']],
    ['Ты теряешь 5 хитов.', ['hp-loss']],
    ['Стрела задевает тебя.', ['hp-loss']],
  ])('«%s» → %j', (text, kinds) => {
    expect(textClaims(text)).toEqual(kinds)
  })

  it.each([
    'Ты ничего не находишь.',
    'Ты не получаешь ответа.',
    'Ты находишь взглядом трактирщика.',
    'Ты получаешь преимущество на следующую проверку.',
    'Стражник не убиваешь… то есть не убивает тебя, а лишь хмурится.',
    'Ты пытаешься убедить стражника — он колеблется.',
    'Люстра с грохотом рушится на стол, разбрасывая свечи.',
  ])('без утверждений: «%s»', (text) => {
    expect(textClaims(text)).toEqual([])
  })
})
